/**
 * Regenerates the machine-made half of the rebuild pack (docs/rebuild/generated):
 * the exact database schema, and inventories of every API route, page,
 * module and tunable constant, read straight from the code so they cannot
 * drift from it. Run after any change:
 *
 *   PGURL=postgres://postgres@localhost:5433/postgres npx tsx --tsconfig tsconfig.scripts.json scripts/rebuild-pack.ts
 *
 * PGURL is any local Postgres 16 server; a scratch database is created on it,
 * every migration applied in order, dumped, and dropped again. Add --verify
 * to also rebuild a database from the generated files alone and run the full
 * rule and RLS tests against it. Without PGURL
 * the database files are left as they are and only the code inventories are
 * rebuilt.
 */
import { execFileSync, spawnSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const ROOT = process.cwd()
const OUT = join(ROOT, 'docs', 'rebuild', 'generated')
mkdirSync(OUT, { recursive: true })

const HEADER = (what: string) =>
  `<!-- Generated by scripts/rebuild-pack.ts from the code. Do not edit by hand: change the code and rerun. -->\n\n# ${what}\n\n`

function walk(dir: string, match: (f: string) => boolean, out: string[] = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, match, out)
    else if (match(p)) out.push(p)
  }
  return out.sort()
}

/** The first /** … *\/ block in a file, as plain text. */
function docComment(src: string) {
  const m = src.match(/\/\*\*([\s\S]*?)\*\//)
  if (!m) return ''
  return m[1]
    .split('\n')
    .map((l) => l.replace(/^\s*\*\s?/, '').trimEnd())
    .join('\n')
    .trim()
}

/** A balanced `{ … }` or `( … )` starting at index i. */
function balanced(src: string, i: number) {
  const open = src[i]
  const close = open === '{' ? '}' : open === '(' ? ')' : ']'
  let depth = 0
  for (let j = i; j < src.length; j++) {
    if (src[j] === open) depth++
    else if (src[j] === close && --depth === 0) return src.slice(i, j + 1)
  }
  return src.slice(i)
}

/** Every `const xxx = z.object(…)` (and similar zod schemas) verbatim. */
function zodSchemas(src: string) {
  const out: string[] = []
  const re = /const (\w*[sS]chema\w*)\s*=\s*z\b/g
  let m: RegExpExecArray | null
  while ((m = re.exec(src))) {
    const start = m.index
    let i = src.indexOf('(', start)
    if (i < 0) continue
    let text = src.slice(start, i) + balanced(src, i)
    // Chained calls: .refine(...), .superRefine(...), .transform(...)
    let rest = src.slice(start + text.length)
    while (/^\s*\.\w+\(/.test(rest)) {
      const dot = rest.indexOf('(')
      const call = rest.slice(0, dot) + balanced(rest, dot)
      text += call
      rest = rest.slice(call.length)
    }
    out.push(text.trim())
  }
  return out
}

function roles(src: string) {
  const m = src.match(/require(?:Api)?Session\(\s*(\[[^\]]*\]|[A-Z_]+)/)
  if (!m) return src.includes('cronAuthorized') ? 'cron (Bearer CRON_SECRET)' : 'public / own check'
  return m[1].replace(/\s+/g, ' ')
}

function routePath(file: string, base: string, suffix: string) {
  const rel = relative(base, file).split(sep).join('/')
  const p = '/' + rel.replace(new RegExp(`/?${suffix}$`), '')
  return p === '/' ? '/' : p.replace(/\/$/, '')
}

