/**
 * Turns the staff guide (src/components/staff-guide.tsx) into plain text for
 * the staff helper AI (src/lib/support-assistant.ts), so the AI answers from
 * exactly what staff read. Writes src/lib/generated/staff-guide-text.ts.
 *
 *   npx tsx --tsconfig tsconfig.scripts.json scripts/make-guide-knowledge.ts          # write it
 *   npx tsx --tsconfig tsconfig.scripts.json scripts/make-guide-knowledge.ts --check  # fail if stale
 *
 * Run it after any change to the staff guide or lib/field-guide.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { StaffGuide } from '@/components/staff-guide'

const OUT = join(__dirname, '..', 'src', 'lib', 'generated', 'staff-guide-text.ts')

const ENTITIES: Record<string, string> = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", '#x27': "'", nbsp: ' ' }

export function guideText(html: string): string {
  let s = html
    // The video player and the contents chips are not guide text.
    .replace(/<video[\s\S]*?<\/video>/g, '')
    .replace(/<nav[\s\S]*?<\/nav>/g, '')
    // Screenshots and their captions describe pictures the AI cannot show.
    .replace(/<figure[\s\S]*?<\/figure>/g, '')
    // A numbered step: "3. Tap Try again."
    .replace(/<li[^>]*>\s*<span[^>]*>(\d+)<\/span>/g, '\n$1. ')
    .replace(/<h2[^>]*>/g, '\n\n## ')
    .replace(/<h3[^>]*>/g, '\n\n### ')
    .replace(/<summary[^>]*>/g, '\nQ: ')
    .replace(/<\/summary>/g, '\nA: ')
    .replace(/<li[^>]*>/g, '\n- ')
    .replace(/<(p|div|figcaption|details|ol|ul|section)[^>]*>/g, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&(#?\w+);/g, (m, e: string) => ENTITIES[e] ?? m)
  s = s
    .split('\n')
    .map((l) => l.replace(/\s+/g, ' ').trim())
    .filter((l, i, a) => l !== '' || (a[i - 1] ?? '') !== '')
    .join('\n')
    // A "- " line left empty by a step that starts on the next line.
    .replace(/^-\n/gm, '')
    .replace(/^(Q: .*?)\s*\+$/gm, '$1')
    .replace(/^A:\n+/gm, 'A: ')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
  // The video's chapter list comes first; the guide starts at its first section.
  const start = s.indexOf('\n## ', s.startsWith('## Watch') ? 1 : 0)
  return start > 0 && s.startsWith('## Watch') ? s.slice(start + 1) : s
}

/** The generated file's contents, from the guide as it is now. */
export function guideFile(): { text: string; file: string } {
  const text = guideText(renderToStaticMarkup(createElement(StaffGuide)))
  const file = `// Generated by scripts/make-guide-knowledge.ts from the staff guide. Do not edit by hand.
// The staff helper AI answers from this text (src/lib/support-assistant.ts).
export const STAFF_GUIDE_TEXT = ${JSON.stringify(text)}
`
  return { text, file }
}

export const GUIDE_TEXT_FILE = OUT

if (require.main === module) {
  const { text, file } = guideFile()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      // missing
    }
    if (current !== file) {
      console.error('FAIL src/lib/generated/staff-guide-text.ts is out of date: run scripts/make-guide-knowledge.ts')
      process.exit(1)
    }
    console.log(`ok   the AI's copy of the staff guide is current (${text.length} characters)`)
  } else {
    writeFileSync(OUT, file)
    console.log(`wrote src/lib/generated/staff-guide-text.ts (${text.length} characters)`)
  }
}
